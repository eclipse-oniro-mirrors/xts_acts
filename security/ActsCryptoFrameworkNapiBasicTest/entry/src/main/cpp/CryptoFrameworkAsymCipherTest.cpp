struct SM2EnCipherParams {
    const char *algoName;
    OH_CryptoKeyPair *keyPair;
    size_t blockSize;
    Crypto_DataBlob *msg;
    Crypto_DataBlob *cipherText;
    int *cipherIndex;
};
    
static void OHTEST_DoSM2EncryptCipher(const SM2EnCipherParams &params)
{
    OH_CryptoAsymCipher *ctx = nullptr;
    int quotient = params.msg->len / params.blockSize;
    int remainder = params.msg->len % params.blockSize;
    uint8_t *data = params.msg->data;
    size_t len = params.msg->len;
    Crypto_DataBlob *dataBlob = params.msg;
    size_t cipherLen = 0;
    Crypto_DataBlob cipherData = {.data = nullptr, .len = 0};

    params.cipherText->data = static_cast<uint8_t*>(malloc(params.cipherText->len));
    uint8_t *tmp = params.cipherText->data;
    EXPECT_TRUE(params.cipherText->data != nullptr);
    if (params.cipherText->data == nullptr) {
        return;
    }

    EXPECT_EQ(OH_CryptoAsymCipher_Create(params.algoName, &ctx), CRYPTO_SUCCESS);
    EXPECT_TRUE(ctx != nullptr);
    EXPECT_EQ(OH_CryptoAsymCipher_Init(ctx, CRYPTO_ENCRYPT_MODE, params.keyPair), CRYPTO_SUCCESS);

    for (int i = 0; i < quotient; i++) {
        dataBlob->len = params.blockSize;
        EXPECT_EQ(OH_CryptoAsymCipher_Final(ctx, dataBlob, &cipherData), CRYPTO_SUCCESS);

        EXPECT_EQ(SafeMemcpy(params.cipherText->data, params.cipherText->len - cipherLen,
            cipherData.data, cipherData.len), 0);

        params.cipherText->data += cipherData.len;
        cipherLen += cipherData.len;
        dataBlob->data += params.blockSize;
        params.cipherIndex[i] = cipherData.len;
        OH_Crypto_FreeDataBlob(&cipherData);
    }

    if (remainder) {
        dataBlob->len = remainder;
        EXPECT_EQ(OH_CryptoAsymCipher_Final(ctx, dataBlob, &cipherData), CRYPTO_SUCCESS);
        EXPECT_EQ(SafeMemcpy(params.cipherText->data, params.cipherText->len - cipherLen,
            cipherData.data, cipherData.len), 0);
        params.cipherText->data += cipherData.len;
        cipherLen += cipherData.len;
        params.cipherIndex[quotient] = cipherData.len;
    }

    dataBlob->data = data;
    dataBlob->len = len;
    params.cipherText->data = tmp;
    params.cipherText->len = cipherLen;

    OH_CryptoAsymCipher_Destroy(ctx);
    OH_Crypto_FreeDataBlob(&cipherData);
}
    
struct SM2DeCipherParams {
    const char *algoName;
    OH_CryptoKeyPair *keyPair;
    size_t blockSize;          // 加密时需要，解密时可忽略或保留
    Crypto_DataBlob *msg;      // 输入明文或密文块
    Crypto_DataBlob *cipherText; // 输出密文或解密后明文
    int *cipherIndex;          // 分段长度数组
};
    
static void OHTEST_DoSM2DecryptCipher(const SM2DeCipherParams &params)
{
    OH_CryptoAsymCipher *ctx = nullptr;
    uint8_t *data = params.msg->data;
    size_t len = params.msg->len;
    Crypto_DataBlob *dataBlob = params.msg;
    size_t cipherLen = 0;
    Crypto_DataBlob cipherData = {.data = nullptr, .len = 0};
    int i = 0;

    params.cipherText->data = static_cast<uint8_t*>(malloc(params.cipherText->len));
    uint8_t *tmp = params.cipherText->data;
    EXPECT_TRUE(params.cipherText->data != nullptr);
    if (params.cipherText->data == nullptr) {
        return;
    }

    EXPECT_EQ(OH_CryptoAsymCipher_Create(params.algoName, &ctx), CRYPTO_SUCCESS);
    EXPECT_TRUE(ctx != nullptr);
    EXPECT_EQ(OH_CryptoAsymCipher_Init(ctx, CRYPTO_DECRYPT_MODE, params.keyPair), CRYPTO_SUCCESS);

    while (params.cipherIndex[i] != 0) {
        dataBlob->len = params.cipherIndex[i];
        EXPECT_EQ(OH_CryptoAsymCipher_Final(ctx, dataBlob, &cipherData), CRYPTO_SUCCESS);

        EXPECT_EQ(SafeMemcpy(params.cipherText->data, params.cipherText->len - cipherLen,
            cipherData.data, cipherData.len), 0);

        params.cipherText->data += cipherData.len;
        cipherLen += cipherData.len;
        dataBlob->data += params.cipherIndex[i];
        i++;
        OH_Crypto_FreeDataBlob(&cipherData);
    }

    dataBlob->data = data;
    dataBlob->len = len;
    params.cipherText->data = tmp;
    params.cipherText->len = cipherLen;

    OH_CryptoAsymCipher_Destroy(ctx);
    OH_Crypto_FreeDataBlob(&cipherData);
}

